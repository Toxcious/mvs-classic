/// The derived `Hash` (the variant's index, then a data class's name) into the state hash: constant time.
struct HashInto<'a>(&'a mut crate::state::StateHasher);

impl std::hash::Hasher for HashInto<'_> {
    fn finish(&self) -> u64 {
        self.0.finish()
    }

    fn write(&mut self, bytes: &[u8]) {
        self.0.write_bytes(bytes);
    }
}

impl crate::state::StateHash for BuffClass {
    fn hash_state(&self, h: &mut crate::state::StateHasher) {
        std::hash::Hash::hash(self, &mut HashInto(h));
    }
}
