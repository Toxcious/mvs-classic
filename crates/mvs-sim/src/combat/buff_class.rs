    /// The class of a Blueprint class name: a registered one by its name, else the data's (`None`: the name is not
    /// interned).
    pub fn of(names: &crate::names::Names, s: &str) -> Option<BuffClass> {
        match BuffClass::ALL.iter().find(|c| c.registered_name() == Some(s)) {
            Some(c) => Some(*c),
            None => names.get(s).map(BuffClass::Data),
        }
    }

    /// The Blueprint class name.
    pub fn name(self, names: &crate::names::Names) -> &str {
        match self {
            BuffClass::Data(n) => names.str(n),
            c => c.registered_name().unwrap_or_default(),
        }
    }

