//! The rsqrtss / rcpss tables of `mvs_math::f32::estimate`.
//!
//! `--write <file>` reads the tables off this CPU (one input per entry) and writes them as Rust; it refuses when an
//! entry does not have the layout the module assumes (exponent 126, the 11 low mantissa bits zero). Without it, every
//! float input of rsqrtss, rsqrtps, rcpss and rcpps on this CPU is compared with the module's estimate: that is the
//! check of the layout (one table entry per exponent parity and 12 mantissa bits) and of the special cases.

use mvs_math::f32::estimate::{rcp_estimate, rsqrt_estimate};
use mvs_math_check::hardware::{cpu_name, rcpps, rcpss, rsqrtps, rsqrtss};
use mvs_math_check::par::{Tally, run};
use mvs_math_check::same;
use std::fmt::Write as _;
use std::time::Instant;

fn entry(out: f32, what: &str, index: usize) -> u16 {
    let bits = out.to_bits();
    assert_eq!(bits >> 23, 126, "{what}[{index}] = {bits:#010x}: exponent is not 126");
    assert_eq!(bits & 0x7ff, 0, "{what}[{index}] = {bits:#010x}: low mantissa bits are not zero");
    ((bits >> 11) & 0xfff) as u16
}

fn table(name: &str, values: &[u16], out: &mut String) {
    writeln!(out, "pub(super) static {name}: [u16; {}] = [", values.len()).unwrap();
    for row in values.chunks(16) {
        let cells: Vec<String> = row.iter().map(|v| format!("{v:#05x}")).collect();
        writeln!(out, "    {},", cells.join(", ")).unwrap();
    }
    writeln!(out, "];").unwrap();
}

fn write(path: &str) {
    let rsqrt: Vec<u16> = (0..8192u32)
        .map(|i| {
            let x = f32::from_bits(((127 + (i >> 12)) << 23) | ((i & 0xfff) << 11));
            entry(rsqrtss(x), "RSQRT", i as usize)
        })
        .collect();
    let rcp: Vec<u16> =
        (0..4096u32).map(|i| entry(rcpss(f32::from_bits((127 << 23) | (i << 11))), "RCP", i as usize)).collect();
    let mut s = String::new();
    writeln!(s, "//! Generated by `cargo run -p mvs-math-check --bin zen4-tables -- --write <this file>` on").unwrap();
    writeln!(s, "//! {}; do not edit. Each entry is the 12 leading mantissa bits of the estimate of", cpu_name())
        .unwrap();
    writeln!(s, "//! 2^p (1 + i / 4096) (rsqrt: index p 4096 + i) or of 1 + i / 4096 (rcp), whose exponent is 126.")
        .unwrap();
    writeln!(s).unwrap();
    table("RSQRT", &rsqrt, &mut s);
    writeln!(s).unwrap();
    table("RCP", &rcp, &mut s);
    std::fs::write(path, s).expect("write the table file");
    println!("wrote {path}");
}

fn check() {
    println!("{}", cpu_name());
    let started = Instant::now();
    let parts = run(0, 1 << 32, 1 << 22, |lo, hi| {
        let mut t = Tally::default();
        let mut x = lo;
        while x < hi {
            let v: [f32; 4] = std::array::from_fn(|k| f32::from_bits((x + k as u64) as u32));
            let (rs, rc) = (rsqrtps(v), rcpps(v));
            for k in 0..4 {
                let e = (rsqrt_estimate(v[k]), rcp_estimate(v[k]));
                let hw = [rsqrtss(v[k]), rs[k], rcpss(v[k]), rc[k]];
                let want = [e.0, e.0, e.1, e.1];
                for (n, name) in ["rsqrtss", "rsqrtps", "rcpss", "rcpps"].iter().enumerate() {
                    if !same(hw[n], want[n]) || (hw[n].is_nan() && hw[n].to_bits() != want[n].to_bits()) {
                        t.add(|| {
                            format!(
                                "{name}({:#010x}) = {:#010x}, port {:#010x}",
                                v[k].to_bits(),
                                hw[n].to_bits(),
                                want[n].to_bits()
                            )
                        });
                    }
                }
            }
            x += 4;
        }
        t
    });
    let t = Tally::merge(parts);
    println!(
        "every input of rsqrtss, rsqrtps, rcpss, rcpps: {} mismatches ({:.1} s)",
        t.count,
        started.elapsed().as_secs_f64()
    );
    for e in &t.examples {
        println!("  {e}");
    }
    if t.count != 0 {
        std::process::exit(1);
    }
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    match args.as_slice() {
        [flag, path] if flag == "--write" => write(path),
        [] => check(),
        _ => {
            eprintln!("usage: zen4-tables [--write <estimate_tables.rs>]");
            std::process::exit(2);
        }
    }
}
