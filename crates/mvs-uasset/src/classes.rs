//! CUE4Parse 1.2.2's class registry: every UObject type it registers by name (engine namespaces) whose class or an
//! ancestor below UObject overrides Deserialize or WriteJson, with the C# classes that override, most derived first.
//! A registered type that overrides nothing reads as a plain UObject and is left out; so are game-specific
//! namespaces. The table below is generated from the decompiled CUE4Parse, sorted by name.

/// The chain of a registered name (`AkMediaAsset` -> [`UAkMediaAsset`]); `None` for a name it does not register.
pub fn native_chain(registered: &str) -> Option<&'static [&'static str]> {
    CHAINS.binary_search_by(|(k, _)| (*k).cmp(registered)).ok().map(|i| CHAINS[i].1)
}

/// ObjectTypeRegistry.GetClass: the name, or the name without "_C", when registered.
pub fn registered(name: &str) -> Option<&'static str> {
    let at = |n: &str| CHAINS.binary_search_by(|(k, _)| (*k).cmp(n)).ok().map(|i| CHAINS[i].0);
    at(name).or_else(|| name.strip_suffix("_C").and_then(at))
}

/// The C# classes (most derived first) whose Deserialize / WriteJson an object of a registered type runs; empty for
/// a plain UObject.
pub fn chain_of(reg: Option<&str>) -> &'static [&'static str] {
    reg.and_then(native_chain).unwrap_or(&[])
}

